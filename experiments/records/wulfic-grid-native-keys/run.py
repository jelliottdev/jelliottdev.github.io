"""Summarize the exact pinned 456-row Stage N output."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build() -> dict:
    with (HERE / "source-stage_n_results.tsv").open(encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream, delimiter="\t"))
    assert len(rows) == 456
    byte_rows = [r for r in rows if r["reading"] == "bytes"]
    rune_rows = [r for r in rows if r["reading"] != "bytes"]
    assert len(byte_rows) == 72 and len(rune_rows) == 384
    assert Counter(r["verdict"] for r in rows) == {"fail": 456}
    assert max(float(r["printable"]) for r in byte_rows) == .426
    assert max(float(r["log_lr_nats"]) for r in rune_rows) == 4.63
    return {
        "schema": "liberpedia-wulfic-grid-native-key-results-v1",
        "plan_sha256": sha(HERE / "plan.json"),
        "source_commit": "bf89d3d13aad2b8f2c95ab195cf1b092f250775c",
        "source_table_sha256": sha(HERE / "source-stage_n_results.tsv"),
        "profile_sha256": sha(HERE / "source-profile.json"),
        "total_settings": len(rows), "byte_settings": len(byte_rows), "rune_settings": len(rune_rows),
        "source_passes": 0, "best_printable_fraction": .426, "source_printable_pass": .90,
        "signature_hits": sum(r["signature"] != "-" for r in byte_rows),
        "best_rune_log_lr": 4.63, "source_rune_pass": 30.0,
        "post_replay_diagnostic": "Planted detector controls are generated by the independent checker after the original LP2 source replay; they were not a source preregistration or a full power study."
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = json.dumps(build(), ensure_ascii=False, indent=2) + "\n"
    path = HERE / "results.json"
    if args.check:
        assert path.read_text(encoding="utf-8") == content
        print("Stage N source table and scope: OK")
    else:
        path.write_text(content, encoding="utf-8", newline="\n")
