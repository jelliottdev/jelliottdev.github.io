const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const base=process.env.WIKI_BASE_URL||'http://127.0.0.1:8765/';
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/data/evidence/embedded-payloads.json',route=>route.abort());
 await page.goto(base+'#/reader/lp2-15?view=image');
 await page.locator('.data-notice').waitFor();
 await page.getByRole('button',{name:'Text',exact:true}).click();
 assert.equal(await page.locator('.reader-workspace').getAttribute('data-view'),'text');
 assert(page.url().includes('view=text'));
 await page.locator('#reader-size').fill('26');
 await page.reload();
 await page.locator('.data-notice').waitFor();
 assert.equal(await page.locator('.reader-workspace').getAttribute('data-view'),'text');
 assert.equal(await page.locator('#reader-size').inputValue(),'26');
 await page.getByRole('button',{name:'Image',exact:true}).click();
 await page.evaluate(()=>window.scrollTo(0,document.querySelector('.reader-workspace').offsetTop+420));
 const before=await page.evaluate(()=>scrollY);
 await page.getByRole('button',{name:'Text',exact:true}).click();
 const after=await page.evaluate(()=>scrollY);
 assert(after>=0,'The shorter text view remains usable');
 await page.getByRole('button',{name:'Image',exact:true}).click();
 await page.waitForFunction(expected=>Math.abs(scrollY-expected)<30,before);
 const restored=await page.evaluate(()=>scrollY);
 assert(Math.abs(restored-before)<30,'Image position should be restored');
 await page.locator('#reader-page').selectOption('lp2-16');
 await page.waitForURL('**/#/reader/lp2-16');
 assert.equal(await page.locator('.reader-workspace').getAttribute('data-view'),'image');
 assert.deepEqual(errors,[]);
 const search=await browser.newPage();
 await search.route('**/data/topics.json',route=>route.abort());
 await search.goto(base+'#/search/Atbash');
 await search.locator('.data-notice').waitFor();
 await search.locator('[data-search-kind="page"]').click();
 assert.equal(await search.locator('[data-search-kind="page"]').getAttribute('aria-pressed'),'true');
 assert(search.url().includes('kind=page'),'Search controls must remain bound after a missing-data notice');
 const fast=await browser.newPage();
 await fast.route('**/data/article-search.json',async route=>{await new Promise(resolve=>setTimeout(resolve,2200));await route.continue()});
 const start=Date.now();await fast.goto(base+'#/overview');await fast.locator('.home-intro').waitFor();
 assert(Date.now()-start<1800,'Homepage should render before the delayed optional index');
 await browser.close();
 console.log('PASS: optional-data recovery retains reader controls; view, size, link, and position persist; homepage renders before optional data.');
})().catch(error=>{console.error(error);process.exit(1)});
