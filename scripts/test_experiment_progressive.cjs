const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
const base=process.env.WIKI_BASE_URL||'http://127.0.0.1:8765/';
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 for(const path of ['idea-coverage.json','method-families.json','reported-attempts.json']){
  await page.route(`**/data/${path}`,async route=>{await delay(1900);await route.continue()});
 }
 await page.route('**/data/assistant.json',async route=>{await delay(1900);await route.fulfill({json:{}})});
 const started=Date.now();await page.goto(base+'#/experiments');await page.locator('#experiment-query').waitFor();
 assert(Date.now()-started<1500,'Published experiments should render before supporting files');
 await page.locator('#experiment-query').fill('make it say any sentence');
 await page.locator('#idea-submit').click();
 await page.locator('#experiment-results h2').first().waitFor();
 const result=await page.locator('#experiment-results').innerText();
 await page.getByText('Coverage of this idea',{exact:true}).waitFor();
 assert.equal(await page.locator('#experiment-query').inputValue(),'make it say any sentence');
 assert.equal(await page.locator('#experiment-results').innerText(),result,'Late support data must not replace results');
 assert.deepEqual(errors,[]);
 await page.close();
 const unavailable=await browser.newPage();
 await unavailable.route('**/data/reported-attempts.json',route=>route.abort());
 await unavailable.route('**/data/assistant.json',route=>route.fulfill({json:{}}));
 await unavailable.goto(base+'#/experiments?q=reverse%20primes');
 await unavailable.locator('#reported-attempts').getByText(/prior-work index could not be loaded/).waitFor();
 assert.equal(await unavailable.locator('#experiment-query').inputValue(),'reverse primes');
 await unavailable.close();
 const record=await browser.newPage({viewport:{width:390,height:844}});
 const recordErrors=[];record.on('pageerror',error=>recordErrors.push(error.message));
 await record.route('**/data/method-families.json',async route=>{await delay(1900);await route.continue()});
 const recordStart=Date.now();await record.goto(base+'#/experiments/lp2-row-column-routes');await record.locator('.experiment-article').waitFor();
 assert(Date.now()-recordStart<1500,'Record should render before method-family index');
 await record.getByRole('button',{name:'Rows first'}).click();
 const selected=await record.getByRole('button',{name:'Rows first'}).getAttribute('aria-pressed');
 await record.locator('#experiment-method-guides summary').waitFor();
 assert.equal(await record.getByRole('button',{name:'Rows first'}).getAttribute('aria-pressed'),selected,'Late method guides must not reset the illustration');
 assert.deepEqual(recordErrors,[]);
 const ai=await browser.newPage();
 const fixture={id:'fixture',status:'published',title:'Reverse prime sequence',summary:'A bounded fixture',question:'Does reversal help?',tags:['reverse','primes'],record_type:{id:'method',label:'Bounded solving test'},scope:{pages:['lp2-15'],representation:'runes',procedure:'reverse prime sequence',parameters:'one row',exclusions:'other rows'},finding:'A fixture result',limitations:'One row',outcome:'inconclusive',reproduction:{script:'fixture/run.py',inputs:[],outputs:[]},sources:[],related:[]};
 await ai.route('**/data/experiments.json',route=>route.fulfill({json:{records:[fixture]}}));
 await ai.route('**/data/assistant.json',async route=>{await delay(1600);await route.fulfill({json:{endpoint:'https://assistant.example/ask'}})});
 let requests=0;
 await ai.route('https://assistant.example/ask',route=>{requests++;route.fulfill({status:503,json:{error:'unavailable'}})});
 await ai.goto(base+'#/experiments');await ai.locator('#experiment-query').waitFor();
 await ai.locator('#experiment-query').fill('reverse prime sequence');
 await ai.locator('#idea-submit').click();
 await ai.locator('#experiment-results h2').first().waitFor();
 await ai.locator('#idea-status').getByText('Preparing the comparison…').waitFor();
 await ai.locator('#experiment-answer').getByText(/unavailable/).waitFor();
 assert.equal(requests,1,'A click before configuration arrives should still make exactly one comparison request');
 assert.equal(await ai.locator('#experiment-query').inputValue(),'reverse prime sequence');
 await browser.close();
 console.log('PASS: experiment pages render before optional indexes; late coverage and method guides preserve input, results and controls.');
})().catch(error=>{console.error(error);process.exit(1)});
