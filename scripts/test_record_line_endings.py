"""Fail before catalogue work when Git would change authored record bytes."""
import contextlib
import io
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import unittest
from unittest.mock import patch

import build_experiments as builder


ROOT = Path(__file__).resolve().parents[1]


class RecordLineEndingTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='liberpedia-record-eol-')
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        # Use the real maintained attributes, including scientific -text exceptions.
        (self.root / '.gitattributes').write_bytes((ROOT / '.gitattributes').read_bytes())

    def git(self, *args):
        return subprocess.run(['git', *args], cwd=self.root, check=True,
                              capture_output=True, text=True).stdout

    def record(self, name='ordinary-record', ending=b'\n'):
        path = self.root / 'experiments/records' / name / 'record.json'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b'{"status":"draft"}' + ending)
        return path

    def successful_build(self):
        (self.root / 'data').mkdir()
        (self.root / 'reference').mkdir()
        (self.root / 'data/index.json').write_bytes(b'{"pages":[]}\n')
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(builder.build(self.root), [])
        self.assertTrue((self.root / 'data/experiments.json').exists())

    def reference(self, path, role='inputs'):
        owner = self.record('dependency-owner')
        owner.write_bytes((json.dumps({'status': 'draft', 'reproduction': {
            role: [{'path': path.relative_to(self.root).as_posix(),
                    'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}]
        }}) + '\n').encode('utf-8'))

    def test_real_git_referenced_crlf_record_fails_before_index_validation_or_writes(self):
        self.git('init', '-q')
        path = self.record(ending=b'\r\n')
        self.reference(path)
        # No data/index.json: dependency-byte guard must precede catalogue work.
        self.assertIn('eol: lf', self.git('check-attr', 'text', 'eol', '--',
                                        path.relative_to(self.root).as_posix()))
        before = {p.relative_to(self.root): p.read_bytes()
                  for p in self.root.rglob('*') if p.is_file()}
        with patch.object(builder, 'validate_record', side_effect=AssertionError('validation ran')), \
                patch.object(Path, 'write_text', side_effect=AssertionError('generated text written')), \
                patch.object(Path, 'write_bytes', side_effect=AssertionError('generated bytes written')):
            with self.assertRaisesRegex(ValueError, 'Git normalizes CRLF.*ordinary-record/record.json'):
                builder.build(self.root)
        after = {p.relative_to(self.root): p.read_bytes()
                 for p in self.root.rglob('*') if p.is_file()}
        self.assertEqual(after, before, 'Do not silently normalize source or create outputs')

    def test_lf_record_in_git_builds_without_touching_raw_crlf_evidence(self):
        self.git('init', '-q')
        path = self.record()
        self.reference(path)
        report = path.with_name('report.json')
        raw_text = path.with_name('input.txt')
        report.write_bytes(b'{"raw":true}\r\n')
        raw_text.write_bytes(b'Rune input\r\n')
        self.successful_build()
        self.assertEqual(path.read_bytes(), b'{"status":"draft"}\n')
        self.assertEqual(report.read_bytes(), b'{"raw":true}\r\n')
        self.assertEqual(raw_text.read_bytes(), b'Rune input\r\n')

    def test_real_git_opaque_scientific_record_keeps_crlf(self):
        self.git('init', '-q')
        path = self.record('lp2-spacing-gap-audit', b'\r\n')
        self.reference(path, 'outputs')
        self.assertIn('text: unset', self.git('check-attr', 'text', 'eol', '--',
                                            path.relative_to(self.root).as_posix()))
        self.successful_build()
        self.assertEqual(path.read_bytes(), b'{"status":"draft"}\r\n')

    def test_non_git_fixture_still_accepts_crlf(self):
        path = self.record(ending=b'\r\n')
        self.reference(path)
        self.successful_build()
        self.assertEqual(path.read_bytes(), b'{"status":"draft"}\r\n')

    def test_unreferenced_git_crlf_metadata_is_not_raw_evidence(self):
        self.git('init', '-q')
        path = self.record(ending=b'\r\n')
        self.successful_build()
        self.assertEqual(path.read_bytes(), b'{"status":"draft"}\r\n')

    def test_referenced_output_record_has_the_same_early_guard(self):
        self.git('init', '-q')
        path = self.record(ending=b'\r\n')
        self.reference(path, 'outputs')
        with self.assertRaisesRegex(ValueError, 'Git normalizes CRLF.*ordinary-record/record.json'):
            builder.build(self.root)
        self.assertFalse((self.root / 'data').exists())


if __name__ == '__main__':
    unittest.main()
