"""Maintain complete rotating domains and independently encoded control pins.

Only synthetic Warning controls are run. These assets do not enable a public
search or claim any manuscript coverage. --check never writes.
"""
import argparse
import hashlib
import json
from pathlib import Path

import pinned_domain_controls as controls
import pinned_domain_partitions as partitions
import rotating_domain_sources as sources

ROOT = Path(__file__).resolve().parents[1]
# A maintained source ID never silently adopts a changed question. New sources
# require an explicit new version here; old preparation identities stay intact.
VERSIONS = {
    'rotate-left': ('rotating-left-nine-openings-v1',
                    'd_80bf3646f0c030a499bb0357ba454f2489e7505ca2e871ceb720d6b6e0dd27b8'),
    'rotate-right': ('rotating-right-nine-openings-v1',
                     'd_b4520a6328c46f1a455603903b8e4e494894c053c067bc14f5b8b973e6f908f5'),
}


def artifacts(root=ROOT):
    root = Path(root)
    result, descriptors = {}, []
    for variant, domain in sources.domains(root).items():
        built = controls.build(root, domain)
        source_id, parent_id = VERSIONS[variant]
        if built['manifest']['parentDomainId'] != parent_id:
            raise ValueError('Changed question requires a new maintained source version: ' + variant)
        raw = (partitions.stable(built['manifest']) + '\n').encode('utf-8')
        path = 'data/pinned-domains/' + variant + '-warning-controls.json'
        result[path] = raw
        descriptors.append(dict(
            sourceId=source_id,
            domain=domain, template=built['template'],
            manifestPath=path, manifestSha256=hashlib.sha256(raw).hexdigest()))
    # Trusted metadata travels with the server, not an editable browser request.
    module = ('/* Generated by scripts/build_pinned_domains.py; synthetic controls only. */\n'
              'export default ' + json.dumps(descriptors, ensure_ascii=False, indent=2) + ';\n')
    result['services/idea-assistant/pinned-domain-sources.mjs'] = module.encode('utf-8')
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = artifacts()
    mismatches = []
    for path, raw in expected.items():
        target = ROOT / path
        if args.check:
            if not target.is_file() or target.read_bytes() != raw:
                mismatches.append(path)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
    if mismatches:
        raise SystemExit('Pinned domain assets differ: ' + ', '.join(mismatches))
    print(('Checked' if args.check else 'Built') + ' two complete rotating domains; '
          '5,122 independently encoded full-Warning controls; zero manuscript runs.')


if __name__ == '__main__':
    main()
